import { describe, expect, it } from 'vitest';
import { creatures, plural } from './text';

describe('plural — русское склонение', () => {
  it('единственное число', () => {
    expect(plural(1, 'существо', 'существа', 'существ')).toBe('существо');
    expect(plural(21, 'существо', 'существа', 'существ')).toBe('существо');
  });
  it('малое множественное (2..4)', () => {
    expect(plural(2, 'существо', 'существа', 'существ')).toBe('существа');
    expect(plural(3, 'существо', 'существа', 'существ')).toBe('существа');
  });
  it('множественное (0, 5..20, 11..14)', () => {
    expect(plural(0, 'существо', 'существа', 'существ')).toBe('существ');
    expect(plural(5, 'существо', 'существа', 'существ')).toBe('существ');
    expect(plural(11, 'существо', 'существа', 'существ')).toBe('существ');
    expect(plural(14, 'существо', 'существа', 'существ')).toBe('существ');
  });
  it('creatures() собирает число со словом', () => {
    expect(creatures(1)).toBe('1 существо');
    expect(creatures(4)).toBe('4 существа');
    expect(creatures(7)).toBe('7 существ');
  });
});
